_pool: ConnectionPool | None = None

def now(): return datetime.now(timezone.utc).isoformat()
def _get_pool():
    global _pool
    if _pool is None:
        url=get_settings().database_url.strip()
        if not url.startswith(('postgresql://','postgres://')): raise RuntimeError('DATABASE_URL must be PostgreSQL')
        conninfo=url if 'sslmode=' in url else url+('&' if '?' in url else '?')+'sslmode=require'
        _pool=ConnectionPool(conninfo=conninfo,min_size=1,max_size=10,kwargs={'row_factory':dict_row,'prepare_threshold':None},open=False,timeout=10,max_waiting=100,reconnect_timeout=5,num_workers=1); _pool.open(wait=True)
    return _pool


@contextmanager
def connection():
    with _get_pool().connection() as conn:
        yield conn


def init_db() -> None:
    """Run schema creation with retries for transient PostgreSQL deadlocks."""
    for attempt in range(5):
        try:
            with _get_pool().connection() as c:
                with c.transaction():
                    c.execute("SELECT pg_advisory_xact_lock(836421907)")
                    for statement in SCHEMA_STATEMENTS:
                        c.execute(statement)
            return
        except Exception as exc:
            # SQLSTATE 40P01 is the stable PostgreSQL signal. Keep the text
            # check for pooler/driver wrappers that do not expose sqlstate.
            is_deadlock = getattr(exc, "sqlstate", None) == "40P01" or "deadlock detected" in str(exc).lower()
            if not is_deadlock or attempt == 4:
                raise
            time.sleep(2 ** attempt)

