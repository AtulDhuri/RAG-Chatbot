def list_chatbots(search='',status='',plan='',knowledge_status='',limit=25,offset=0,sort='created_at',direction='desc'):
    allowed={'customer_name','chatbot_name','allowed_domain','status','subscription_plan','created_at','subscription_end_date'}; sort=sort if sort in allowed else 'created_at'; direction='ASC' if direction.lower()=='asc' else 'DESC'; where=[]; args=[]
    if search: where.append('(customer_name ILIKE %s OR chatbot_name ILIKE %s OR allowed_domain ILIKE %s OR email ILIKE %s)'); args += [f'%{search}%']*4
    if status: where.append('c.status=%s'); args.append(status)
    if plan: where.append('c.subscription_plan=%s'); args.append(plan)
    if knowledge_status: where.append('k.knowledge_status=%s'); args.append(knowledge_status)
    clause=(' WHERE '+' AND '.join(where)) if where else ''
    with _get_pool().connection() as c:
        total=c.execute('SELECT count(*) AS count FROM chatbots c LEFT JOIN knowledge_bases k ON k.chatbot_id=c.id'+clause,args).fetchone()['count']
        rows=c.execute(f'SELECT c.*, k.knowledge_status,k.knowledge_base_version,k.pages_crawled,k.pages_found,k.website_name,k.estimated_knowledge_size,k.categories,k.last_analyzed_at,k.total_chunks,k.total_tokens,k.content_hash,k.last_crawled_at,k.crawl_started_at,k.crawl_completed_at,k.embedding_provider,k.source_provider,k.error_details,k.crawl_status FROM chatbots c LEFT JOIN knowledge_bases k ON k.chatbot_id=c.id{clause} ORDER BY c.{sort} {direction} LIMIT %s OFFSET %s',args+[limit,offset]).fetchall()
    return {'items':rows,'total':total}

