def sync_subscription_statuses():
    current=now()
    with _get_pool().connection() as c:
        with c.transaction():
            c.execute("UPDATE chatbots SET status='expired', updated_at=%s WHERE subscription_end_date < %s AND status <> 'suspended'",(current,current))
            c.execute("UPDATE chatbots SET status='active', updated_at=%s WHERE status='expired' AND subscription_start_date <= %s AND subscription_end_date >= %s",(current,current,current))
    return active_chatbots()


def close_pool() -> None:
    """Stop psycopg pool workers during shutdown/reload."""
    global _pool
    if _pool is not None:
        _pool.close(timeout=5.0)
        _pool = None


def crawled_urls(chatbot_id, limit=1000, offset=0):
    """Return distinct source pages from the active knowledge version."""
    with _get_pool().connection() as c:
        return c.execute("""SELECT d.source_url, MAX(d.title) AS title,
            COUNT(*) AS chunk_count, d.knowledge_version
            FROM chatbot_documents d
            JOIN knowledge_bases k ON k.chatbot_id=d.chatbot_id
                AND k.knowledge_base_version=d.knowledge_version
            WHERE d.chatbot_id=%s
            GROUP BY d.source_url, d.knowledge_version
            ORDER BY d.source_url
            LIMIT %s OFFSET %s""", (chatbot_id, limit, offset)).fetchall()
